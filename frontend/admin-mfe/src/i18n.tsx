const localeStorageKey = "admin.locale";

type I18nContextValue = {
  locale: SupportedLocale;
  direction: Direction;
  setLocale: (next: SupportedLocale) => void;
  t: (key: string) => string;
  v: (value: string | null | undefined) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export const I18nProvider = ({ children }: { children: React.ReactNode }) => {
  const [locale, setLocaleState] = useState<SupportedLocale>(() => {
    if (typeof window === "undefined") {
      return "fa";
    }
    const saved = window.localStorage.getItem(localeStorageKey);
    if (saved && saved in messages) {
      return saved as SupportedLocale;
    }
    return "fa";
  });

  const setLocale = (next: SupportedLocale) => {
    setLocaleState(next);
    window.localStorage.setItem(localeStorageKey, next);
  };

  const direction = directions[locale];

  useEffect(() => {
    document.documentElement.setAttribute("dir", direction);
    document.documentElement.setAttribute("lang", locale);
    document.body.setAttribute("dir", direction);
  }, [direction, locale]);

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      direction,
      setLocale,
      t: (key: string) => messages[locale][key] ?? uiMessages[locale][key] ?? messages.en[key] ?? uiMessages.en[key] ?? key,
      v: (input) => {
        if (!input) {
          return "";
        }
        const key = `value.${input.toLowerCase().replace(/-/g, "_")}`;
        return uiMessages[locale][key] ?? uiMessages.en[key] ?? input;
      }
    }),
    [locale, direction]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = () => {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return value;
};
